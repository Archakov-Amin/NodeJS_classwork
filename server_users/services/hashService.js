// Импортируем библиотеку bcrypt для работы с хешированием паролей
import bcrypt from "bcrypt";

// Создаем класс HashService для группировки функций безопасности
class HashService {
    // Асинхронный метод для создания хеша (шифрования) пароля
    async hashPassword (password) {
        // Блок try для отлавливания возможных ошибок при выполнении кода
        try {
            // Генерируем "соль" со сложностью 10 для защиты от подбора паролей
            const salt = await bcrypt.genSalt(10);

            // Создаем безопасный хеш пароля, используя сгенерированную соль
            const hash = await bcrypt.hash(password, salt);

            // Возвращаем готовый хеш из метода
            return hash;
        } catch (err) { // Если на каком-то этапе произошла ошибка
            // Выбрасываем новое исключение с понятным текстом ошибки
            throw new Error("Ошибка при хешировании пароля");
        }
    }

    // Асинхронный метод для проверки, подходит ли введенный пароль к хешу
    async comparePassword (password, hash) {
        // Блок try для безопасного выполнения сравнения
        try {
            // Сравниваем чистый пароль с хешем из базы данных и возвращаем true или false
            return await bcrypt.compare(password, hash);
        } catch (err) { // Если при сравнении что-то пошло не так
            // Выбрасываем исключение с текстом об ошибке проверки
            throw new Error("Ошибка при сравнении паролей");
        }
    }
}

// Экспортируем уже созданный объект (экземпляр) этого класса для использования в других файлах
export default new HashService();
